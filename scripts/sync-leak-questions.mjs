// Writes supabase/functions/_shared/leak-questions.ts from src/lib/leak-test.ts, so the
// report generator (which runs in the edge-functions container and cannot import from src)
// always uses the same question wording as the site. Run after editing the questions:
//   npm run sync:questions
import { buildSync } from 'esbuild';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const tmp = path.join(os.tmpdir(), `leak-test-${process.pid}.mjs`);
buildSync({ entryPoints: [path.join(root, 'src/lib/leak-test.ts')], outfile: tmp, bundle: true, format: 'esm', platform: 'node', logLevel: 'error' });
const lib = await import(pathToFileURL(tmp).href);
fs.rmSync(tmp, { force: true });

const tmp2 = path.join(os.tmpdir(), `systems-${process.pid}.mjs`);
buildSync({ entryPoints: [path.join(root, 'src/lib/systems.ts')], outfile: tmp2, bundle: true, format: 'esm', platform: 'node', logLevel: 'error' });
const catalog = await import(pathToFileURL(tmp2).href);
fs.rmSync(tmp2, { force: true });

const questions = lib.QUESTIONS.map((q) => ({ areaId: q.areaId, areaName: q.areaName, text: q.text }));
const answers = lib.ANSWERS.map((a) => a.label);
const out = `// GENERATED by scripts/sync-leak-questions.mjs from src/lib/leak-test.ts. Do not edit by hand.
export const LEAK_QUESTIONS: { areaId: string; areaName: string; text: string }[] = ${JSON.stringify(questions, null, 2)};

/** Labels for answers 0 to 4. */
export const LEAK_ANSWER_LABELS: string[] = ${JSON.stringify(answers)};

/** The six pillars in the order their scores are stored. */
export const LEAK_AREA_IDS: string[] = ${JSON.stringify([...new Set(questions.map((q) => q.areaId))])};
`;
const systems = catalog.SYSTEMS.map((s) => ({ id: s.id, kind: s.kind, pillar: s.pillar ?? null, name: s.name, goal: s.goal, status: s.status, includes: s.includes ?? [] }));
const full = out + `
/** The Breadmaker catalog: systems (one per leak pillar) and the programs that build them. */
export const LEAK_CATALOG: { id: string; kind: string; pillar: string | null; name: string; goal: string; status: string; includes: string[] }[] = ${JSON.stringify(systems, null, 2)};
`;
fs.writeFileSync(path.join(root, 'supabase/functions/_shared/leak-questions.ts'), full);
console.log(`wrote ${questions.length} questions`);
